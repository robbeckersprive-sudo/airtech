"""Uitvoeringen (ATEX / food-grade) per component: mechanism complete, data confirmed by Airtechnic only.

The repository does not know which versions Airtechnic supplies per component. Every `executions` value in
category_data.option(...) / cyclone_category_data is therefore only a *candidate*; nothing is shown on a page until
the (category, variant, execution) triple is in CONFIRMED. CONFIRMED stays empty until Airtechnic fills in
docs/uitvoeringen-matrix.csv and runs `python tools/import_executions.py` (README: "Uitvoeringen (ATEX / food-grade)").

Terminology (README): say "ATEX-uitvoering mogelijk" / "food-grade uitvoering". Never "ATEX-gecertificeerd",
"EHEDG-gecertificeerd" or "FDA-approved" unless Airtechnic confirms and substantiates it per product.
"""

ATEX_ARTICLE = 'kennis-atex-explosieveiligheid.html'

# Fixed vocabulary. Extendable (e.g. 'slijtvast', 'rvs'), but only add a value together with its copy here.
EXECUTIONS = {
    'atex': dict(
        label='ATEX',
        chip='ATEX',
        fact='ATEX-uitvoering mogelijk, categorie in overleg',
        explain='Uitvoering voor gebruik in een zone met explosiegevaar. Categorie en zone stemmen we af op uw zone-indeling.',
        href=ATEX_ARTICLE,
        link_text='Lees over ATEX en explosieveiligheid',
    ),
    'food': dict(
        label='Food-grade',
        chip='Food-grade',
        fact='Uitvoering voor productcontact met levensmiddelen mogelijk',
        explain='Food-grade uitvoering: materialen geschikt voor contact met levensmiddelen en een hygiënisch ontwerp.',
        href='sectoren-food.html',
        link_text='Bekijk de sector food',
    ),
}

# (category slug, variant, execution) confirmed by Airtechnic. Leave empty: filled only by tools/import_executions.py.
# >>> CONFIRMED (generated by tools/import_executions.py; do not edit by hand)
CONFIRMED = frozenset()
# <<< CONFIRMED


def confirmed(category, variant, candidates=()):
    """Execution keys to show for one uitvoering, in EXECUTIONS order. Only confirmed triples count;
    `candidates` (the data's `executions` field) is not needed for display but documents intent."""
    return tuple(k for k in EXECUTIONS if (category, variant, k) in CONFIRMED)


def category_has_confirmed(category):
    return any(c == category for c, _v, _e in CONFIRMED)

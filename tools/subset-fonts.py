"""Optional asset maintenance: python -m pip install fonttools[woff]==4.64.0

Run after src/build.py. Checked-in outputs need no font tooling on Vercel.
Keep the complete fonts as unicode fallbacks for future content and user input.
"""
from pathlib import Path
from html.parser import HTMLParser
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]

class VisibleText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.skip = False
        self.text = []
    def handle_starttag(self, tag, attrs):
        if tag in ('script', 'style'):
            self.skip = True
        self.text.extend(v for k, v in attrs if k in ('title', 'aria-label', 'alt', 'placeholder') and v)
    def handle_endtag(self, tag):
        if tag in ('script', 'style'):
            self.skip = False
    def handle_data(self, data):
        if not self.skip:
            self.text.append(data)

parser = VisibleText()
for file in sorted(ROOT.glob('*.html')):
    parser.feed(file.read_text(encoding='utf-8'))
characters = set(''.join(parser.text)) | set(map(chr, range(32, 127)))
rules = []
for style in ('normal', 'italic'):
    font = TTFont(ROOT / f'assets/fonts/archivo-{style}-100-900-latin.woff2', recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = ['*']
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=''.join(sorted(characters)))
    subsetter.subset(font)
    target = ROOT / f'assets/fonts/archivo-{style}-site.woff2'
    font.save(target)
    codepoints = ','.join(f'U+{code:04X}' for code in sorted(font.getBestCmap()))
    rules.append(f"@font-face {{ font-family:'Archivo'; font-style:{style}; font-weight:100 900; font-stretch:62% 125%; font-display:swap; src:url(../fonts/{target.name}) format('woff2'); unicode-range:{codepoints}; }}")
    print(f'{target.name}: {target.stat().st_size} bytes')
for width, family in ((112, 'Archivo Headline Italic'), (100, 'Archivo Display Italic')):
    font = TTFont(ROOT / 'assets/fonts/archivo-italic-100-900-latin.woff2', recalcTimestamp=False)
    instantiateVariableFont(font, {'wght': 300, 'wdth': width}, inplace=True)
    options = subset.Options()
    options.layout_features = ['*']
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=''.join(sorted(characters)))
    subsetter.subset(font)
    target = ROOT / f'assets/fonts/archivo-italic-300-{width}-site.woff2'
    font.save(target)
    # The complete Archivo family remains the fallback for characters outside the subset.
    codepoints = ','.join(f'U+{code:04X}' for code in sorted(font.getBestCmap()))
    rules.append(f"@font-face {{ font-family:'{family}'; font-style:italic; font-weight:300; font-display:swap; src:url(../fonts/{target.name}) format('woff2'); unicode-range:{codepoints}; }}")
    print(f'{target.name}: {target.stat().st_size} bytes')
css = ROOT / 'assets/css/fonts.css'
marker = '/* Site character subsets; generated by tools/subset-fonts.py. */'
base = css.read_text(encoding='utf-8').split(marker)[0].rstrip()
css.write_bytes((base + '\n\n' + marker + '\n' + '\n'.join(rules) + '\n').encode('utf-8'))
